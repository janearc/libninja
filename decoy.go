package libninja

import (
	"fmt"
	"go/ast"
	"go/token"
	"go/types"
	"path/filepath"
	"regexp"
	"strings"
)

// mockgenMark is what mockgen writes at the top of every file it makes.
const mockgenMark = "Code generated by MockGen. DO NOT EDIT."

// mockOf is what mockgen says above each mock it makes: the mock's name,
// and the interface it is a mock of.
var mockOf = regexp.MustCompile(`^(\w+) is a mock of (\w+) interface`)

// mock is a type mockgen made. It holds the mock's name and constructor,
// and the interface it stands in for with that interface's name.
type mock struct {
	name     string
	made     *types.Func
	face     *types.Interface
	faceName string
}

// decoys is every stand-in tests make where mockgen made one already.
// That is a mock no test makes and a type a test writes for a mocked
// interface. So is a package variable a test swaps. the maintainer, 10-23: "we
// need to verify they are being used."
func (read reading) decoys() []finding {
	mocks := read.mocks()
	found := read.unmade(mocks)
	found = append(found, read.handmade(mocks)...)
	return append(found, read.swapped()...)
}

// mocks is every mock mockgen made in the module, each matched to the
// interface in sight it is a mock of.
func (read reading) mocks() []mock {
	faces := read.namedInterfaces()
	var found []mock
	for _, pkg := range read.plain() {
		for _, file := range pkg.Syntax {
			if !madeByMockgen(file) {
				continue
			}
			for _, decl := range file.Decls {
				made := mocksIn(pkg.Types, decl, faces)
				found = append(found, made...)
			}
		}
	}
	return found
}

// madeByMockgen is whether mockgen wrote a file.
func madeByMockgen(file *ast.File) bool {
	return ast.IsGenerated(file) &&
		strings.Contains(file.Comments[nothing].Text(), mockgenMark)
}

// mocksIn is the mocks a declaration of a mockgen file declares, by
// the comment mockgen writes above each.
func mocksIn(pkg *types.Package, decl ast.Decl,
	faces []*types.TypeName) []mock {
	gen, ok := decl.(*ast.GenDecl)
	if !ok || gen.Tok != token.TYPE {
		return nil
	}
	said := mockOf.FindStringSubmatch(gen.Doc.Text())
	if said == nil {
		return nil
	}
	name, faceName := said[mockName], said[mockedName]
	made, ok := pkg.Scope().Lookup("New" + name).(*types.Func)
	held, isType := pkg.Scope().Lookup(name).(*types.TypeName)
	if !ok || !isType {
		return nil
	}
	pointer := types.NewPointer(held.Type())
	for _, face := range faces {
		mocked := face.Type().Underlying().(*types.Interface)
		if face.Name() == faceName &&
			types.Implements(pointer, mocked) {
			return []mock{{name, made, mocked, faceName}}
		}
	}
	return nil
}

// mockName is where mockOf's match holds the mock's name. It is the
// first group as regexp numbers them, defined so.
const mockName = 1

// mockedName is where mockOf's match holds the interface's name: its
// second group, defined so.
const mockedName = 2

// namedInterfaces is every named interface in sight of the module: its
// own and those of every package it imports however deep.
func (read reading) namedInterfaces() []*types.TypeName {
	sight := namedSight{visited: map[*types.Package]bool{}}
	for _, pkg := range read.pkgs {
		sight.visit(pkg.Types)
	}
	return sight.found
}

// namedSight is a walk through packages and everything they import: the
// packages seen, and the named interfaces found in them.
type namedSight struct {
	visited map[*types.Package]bool
	found   []*types.TypeName
}

// visit takes in a package's named interfaces and then those of
// everything it imports. Each package is taken in once. The guard holds
// the whole walk, so a walk without it finds nothing.
func (sight *namedSight) visit(pkg *types.Package) {
	if !sight.visited[pkg] {
		sight.visited[pkg] = true
		sight.found = append(sight.found, namedInterfacesOf(pkg)...)
		for _, imported := range pkg.Imports() {
			sight.visit(imported)
		}
	}
}

// namedInterfacesOf is every named interface a package declares.
func namedInterfacesOf(pkg *types.Package) []*types.TypeName {
	var found []*types.TypeName
	for _, typeName := range typeNames(pkg) {
		if types.IsInterface(typeName.Type()) {
			found = append(found, typeName)
		}
	}
	return found
}

// unmade is every mock whose constructor no test calls.
func (read reading) unmade(mocks []mock) []finding {
	var found []finding
	for _, each := range mocks {
		if read.madeByATest(each.made) {
			continue
		}
		seen := fmt.Sprintf("%s is a mock of %s that no test makes.",
			each.name, each.faceName)
		student := read.address(each.made.Pkg().Path())
		found = append(found, finding{decoy, student,
			read.at(each.made), seen, ""})
	}
	return found
}

// madeByATest is whether any test calls a function.
func (read reading) madeByATest(made *types.Func) bool {
	for _, each := range read.uses[read.key(made)] {
		if each.test {
			return true
		}
	}
	return false
}

// handmade is every type a test file declares that stands in for an
// interface mockgen made a mock of. One that holds the mock inside it
// is the mock, worn.
func (read reading) handmade(mocks []mock) []finding {
	var found []finding
	for _, each := range read.files() {
		if !each.test() {
			continue
		}
		for node := range ast.Preorder(each.file) {
			spec, ok := node.(*ast.TypeSpec)
			if !ok {
				continue
			}
			stood := read.standIn(each, spec, mocks)
			found = append(found, stood...)
		}
	}
	return found
}

// standIn is the finding a test's type makes when it answers an
// interface that has a mock, or none.
func (read reading) standIn(each source, spec *ast.TypeSpec,
	mocks []mock) []finding {
	declared := each.pkg.TypesInfo.Defs[spec.Name].Type()
	if types.IsInterface(declared) || wearsAMock(declared, mocks) {
		return nil
	}
	pointer := types.NewPointer(declared)
	student := read.address(each.pkg.PkgPath)
	for _, held := range mocks {
		if types.Implements(pointer, held.face) {
			seen := fmt.Sprintf("%s stands in for %s, "+
				"which has a mock: %s.", spec.Name.Name,
				held.faceName, held.name)
			at := read.at(spec)
			return []finding{{decoy, student, at, seen, ""}}
		}
	}
	return nil
}

// wearsAMock is whether a struct holds a mock as an embedded field.
func wearsAMock(declared types.Type, mocks []mock) bool {
	structure, ok := declared.Underlying().(*types.Struct)
	if !ok {
		return false
	}
	for field := range structure.Fields() {
		if field.Embedded() && isAMock(field.Type(), mocks) {
			return true
		}
	}
	return false
}

// isAMock is whether a type is one of the mocks, or a pointer to one.
func isAMock(held types.Type, mocks []mock) bool {
	if pointer, ok := held.(*types.Pointer); ok {
		held = pointer.Elem()
	}
	named, ok := held.(*types.Named)
	if !ok {
		return false
	}
	for _, each := range mocks {
		if named.Obj().Name() == each.name &&
			named.Obj().Pkg() == each.made.Pkg() {
			return true
		}
	}
	return false
}

// swapped is every package variable a test writes, of those the module's
// code declares outside its tests. Each is found at its declaration,
// with the first place a test swaps it.
func (read reading) swapped() []finding {
	first := map[*types.Var]token.Position{}
	var order []*types.Var
	for _, each := range read.files() {
		if !each.test() {
			continue
		}
		info := each.pkg.TypesInfo
		for node := range ast.Preorder(each.file) {
			for _, target := range targets(node) {
				held := read.swappedVar(info, target)
				_, seen := first[held]
				if held != nil && !seen {
					first[held] = read.at(target)
					order = append(order, held)
				}
			}
		}
	}
	var found []finding
	for _, held := range order {
		at := first[held]
		seen := fmt.Sprintf("Tests swap %s, first at %s:%d.",
			held.Name(), filepath.Base(at.Filename), at.Line)
		student := read.address(held.Pkg().Path())
		found = append(found, finding{decoy, student, read.at(held),
			seen, ""})
	}
	return found
}

// targets is what a statement writes. That is an assignment's left side,
// or what ++ or -- changes. Names a := defines are new and local, so the
// package variables among its targets are none.
func targets(node ast.Node) []ast.Expr {
	switch statement := node.(type) {
	case *ast.AssignStmt:
		return statement.Lhs
	case *ast.IncDecStmt:
		return []ast.Expr{statement.X}
	}
	return nil
}

// swappedVar is the package variable an assignment's target writes
// through any fields, indexes or pointers. It is nil unless the
// module's code declares that variable outside its tests.
func (read reading) swappedVar(info *types.Info,
	target ast.Expr) *types.Var {
	switch target := target.(type) {
	case *ast.Ident:
		return read.codeVar(info.Uses[target])
	case *ast.SelectorExpr:
		if held := read.codeVar(info.Uses[target.Sel]); held != nil {
			return held
		}
		return read.swappedVar(info, target.X)
	case *ast.IndexExpr:
		return read.swappedVar(info, target.X)
	case *ast.StarExpr:
		return read.swappedVar(info, target.X)
	case *ast.ParenExpr:
		return read.swappedVar(info, target.X)
	}
	return nil
}

// codeVar is a name as a package variable the module declares outside
// its tests, or nil.
func (read reading) codeVar(used types.Object) *types.Var {
	held, ok := used.(*types.Var)
	if !ok || held.Pkg() == nil || held.Parent() != held.Pkg().Scope() ||
		!read.inModule(held.Pkg().Path()) ||
		strings.HasSuffix(read.at(held).Filename, "_test.go") {
		return nil
	}
	return held
}
